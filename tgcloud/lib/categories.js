export const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е');

export function wordsOf(text) {
  return norm(text).split(/[^a-zа-я0-9/]+/i).filter(Boolean);
}

// Основа слова для выученных ключевых слов: «шаурму» и «шаурма» → «шаур».
export function stemWord(w) {
  w = norm(w);
  if (w.length <= 4) return w;
  if (w.length <= 6) return w.slice(0, w.length - 1);
  return w.slice(0, w.length - 2);
}

function matchesStem(words, padded, stem) {
  // «слово » с пробелом в конце — только точное совпадение слова или фразы.
  if (stem.endsWith(' ')) {
    const t = stem.trim();
    return t.includes(' ') ? padded.includes(' ' + t + ' ') : words.includes(t);
  }
  if (stem.includes(' ')) return padded.includes(' ' + stem);
  return words.some((w) => w.startsWith(stem));
}

export function hasIncomeHint(text) {
  const words = wordsOf(text);
  const padded = ' ' + words.join(' ') + ' ';
  return INCOME_HINTS.some((s) => matchesStem(words, padded, s));
}

